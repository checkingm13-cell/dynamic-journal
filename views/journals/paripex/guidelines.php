<div class="author-guideline-text">
<h3>1. Format & Style</h3>
<p><b>Manuscripts:</b> All manuscripts submission should be through online to be Uploaded on the website or email on Editor@paripex.in. A single word file should consist content in double space on with one inch margine on all sides. The single word file should consist title page, abstract, main text, tables, charts, images at its approriate places and references at last as per APA guidelines.</p>
<p><b>Cover Page:</b> Manuscripts of a paper should have a cover page providing the title of the paper, the name(s), address, phone, fax numbers and e-mail address of all authors and acknowledgments, if any. Please restrict the author - related information only to cover page. Further, please mention the subject under which the paper should be included.</p>
<p><b>Abstract:</b> Following the cover page, there should be an abstract page, which should contain the title of paper, the subtitle "Abstract" and a summary of the paper in double space. It should be around 150-300 words in length along with three to four key words. The text of the paper should not start on this page, but on a fresh page. References should be cited in the style prescribed in the publication manual of the American Psychological Association (APA Guidelines).</p>
<p><b>Figures & Tables:</b> Each figure/table should be numbered, titled. The position of figure or table should be placed at appropriate place within the article only -</p>
<p><b>Length of the Papers:</b> The total length of the paper should not exceed 2000 words (Includes abstract, table, chart, reference etc). Authors are requested to strictly follow the prescribed length. For every additional 750 words an extra Rs. 500/- will be charged.</p>
